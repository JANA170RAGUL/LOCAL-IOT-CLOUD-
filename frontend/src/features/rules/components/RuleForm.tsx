import React, { useState } from 'react';
import { useForm, Controller } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import { z } from 'zod';
import {
  Box,
  Button,
  Dialog,
  DialogActions,
  DialogContent,
  DialogTitle,
  TextField,
  MenuItem,
  Grid,
  Typography,
  Divider,
} from '@mui/material';
import { HierarchySelector, type HierarchySelection } from '../../../components/HierarchySelector';
import { useSensorsQuery } from '../../sensors/hooks/useSensors';
import type { BackendRule, RuleCreate, RuleUpdate } from '../types';

const ruleSchema = z.object({
  code: z.string().min(2, 'Code must be at least 2 characters').regex(/^[a-zA-Z0-9_\-]+$/, 'Invalid characters'),
  name: z.string().min(2, 'Name must be at least 2 characters'),
  description: z.string().optional(),
  sensor_id: z.string().min(1, 'Sensor is required'),
  condition: z.enum(['>', '<', '>=', '<=', '==', '!=', 'BETWEEN', 'OUTSIDE RANGE']),
  threshold: z.number(),
  severity: z.enum(['INFO', 'WARNING', 'CRITICAL', 'EMERGENCY']),
  enabled: z.boolean(),
  cooldown_seconds: z.number().min(0),
  action_type: z.enum(['CREATE_ALERT', 'EMAIL', 'WEBHOOK', 'MQTT_PUBLISH', 'SMS', 'PUSH_NOTIFICATION']),
  action_config: z.record(z.string(), z.any()),
});

type RuleFormData = z.infer<typeof ruleSchema>;

export interface RuleFormProps {
  open: boolean;
  onClose: () => void;
  onSubmit: (data: RuleCreate | RuleUpdate) => void;
  initialData?: BackendRule;
  title: string;
}

export const RuleForm: React.FC<RuleFormProps> = ({ open, onClose, onSubmit, initialData, title }) => {
  // We need to pick a device before we can pick a sensor
  const [hierarchy, setHierarchy] = useState<HierarchySelection>({
    orgId: '',
    tenantId: '',
    projectId: '',
    gatewayId: '',
    deviceId: '',
  });

  const { data: sensorsData } = useSensorsQuery(hierarchy.deviceId || '', 1, 100);

  const {
    control,
    handleSubmit,
    watch,
    setValue,
    reset,
    formState: { errors },
  } = useForm<RuleFormData>({
    resolver: zodResolver(ruleSchema),
    defaultValues: initialData
      ? {
          code: initialData.code,
          name: initialData.name,
          description: initialData.description || '',
          sensor_id: initialData.sensor_id,
          condition: initialData.condition,
          threshold: initialData.threshold,
          severity: initialData.severity,
          enabled: initialData.enabled,
          cooldown_seconds: initialData.cooldown_seconds,
          action_type: initialData.action_type,
          action_config: initialData.action_config || {},
        }
      : {
          code: '',
          name: '',
          description: '',
          sensor_id: '',
          condition: '>',
          threshold: 0,
          severity: 'INFO',
          enabled: true,
          cooldown_seconds: 60,
          action_type: 'CREATE_ALERT',
          action_config: {},
        },
  });

  const actionType = watch('action_type');

  // Handle dialog close and form reset
  const handleClose = () => {
    reset();
    onClose();
  };

  const handleFormSubmit = (data: RuleFormData) => {
    // Inject dynamic action_config if needed before submit
    if (data.action_type === 'CREATE_ALERT') {
      data.action_config = { message: `Alert generated by rule ${data.name}` };
    }
    onSubmit(data);
    handleClose();
  };

  return (
    <Dialog open={open} onClose={handleClose} maxWidth="md" fullWidth>
      <DialogTitle>{title}</DialogTitle>
      <form onSubmit={handleSubmit(handleFormSubmit)}>
        <DialogContent dividers>
          <Typography variant="subtitle1" sx={{ mb: 2, fontWeight: 'bold' }}>
            1. General Settings
          </Typography>
          <Grid container spacing={2} sx={{ mb: 4 }}>
            <Grid size={{ xs: 12, sm: 6 }}>
              <Controller
                name="code"
                control={control}
                render={({ field }) => (
                  <TextField
                    {...field}
                    label="Rule Code"
                    fullWidth
                    size="small"
                    error={!!errors.code}
                    helperText={errors.code?.message}
                    disabled={!!initialData}
                  />
                )}
              />
            </Grid>
            <Grid size={{ xs: 12, sm: 6 }}>
              <Controller
                name="name"
                control={control}
                render={({ field }) => (
                  <TextField
                    {...field}
                    label="Rule Name"
                    fullWidth
                    size="small"
                    error={!!errors.name}
                    helperText={errors.name?.message}
                  />
                )}
              />
            </Grid>
            <Grid size={12}>
              <Controller
                name="description"
                control={control}
                render={({ field }) => (
                  <TextField
                    {...field}
                    label="Description"
                    fullWidth
                    size="small"
                    multiline
                    rows={2}
                    error={!!errors.description}
                    helperText={errors.description?.message}
                  />
                )}
              />
            </Grid>
          </Grid>

          <Divider sx={{ mb: 3 }} />

          <Typography variant="subtitle1" sx={{ mb: 2, fontWeight: 'bold' }}>
            2. Trigger Condition (IF)
          </Typography>
          <Box sx={{ p: 2, bgcolor: 'background.default', borderRadius: 1, mb: 4 }}>
            {!initialData && (
              <Box sx={{ mb: 3 }}>
                <Typography variant="body2" color="text.secondary" sx={{ mb: 1 }}>Select Target Device</Typography>
                <HierarchySelector
                  selection={hierarchy}
                  onChange={(sel) => {
                    setHierarchy(sel);
                    setValue('sensor_id', ''); // Reset sensor when device changes
                  }}
                  maxDepth="device"
                  variant="dropdown"
                />
              </Box>
            )}

            <Grid container spacing={2} sx={{ alignItems: 'center' }}>
              <Grid size={{ xs: 12, sm: 4 }}>
                <Controller
                  name="sensor_id"
                  control={control}
                  render={({ field }) => (
                    <TextField
                      {...field}
                      select
                      label="Sensor"
                      fullWidth
                      size="small"
                      error={!!errors.sensor_id}
                      helperText={errors.sensor_id?.message}
                      disabled={!!initialData || !hierarchy.deviceId}
                    >
                      {sensorsData?.items.map((sensor) => (
                        <MenuItem key={sensor.id} value={sensor.id}>
                          {sensor.name} ({sensor.code})
                        </MenuItem>
                      ))}
                      {!sensorsData?.items.length && (
                        <MenuItem value="" disabled>No sensors found</MenuItem>
                      )}
                    </TextField>
                  )}
                />
              </Grid>
              <Grid size={{ xs: 12, sm: 4 }}>
                <Controller
                  name="condition"
                  control={control}
                  render={({ field }) => (
                    <TextField
                      {...field}
                      select
                      label="Operator"
                      fullWidth
                      size="small"
                      error={!!errors.condition}
                      helperText={errors.condition?.message}
                    >
                      <MenuItem value=">">Greater than (&gt;)</MenuItem>
                      <MenuItem value="<">Less than (&lt;)</MenuItem>
                      <MenuItem value=">=">Greater or equal (&gt;=)</MenuItem>
                      <MenuItem value="<=">Less or equal (&lt;=)</MenuItem>
                      <MenuItem value="==">Equals (==)</MenuItem>
                      <MenuItem value="!=">Not equal (!=)</MenuItem>
                    </TextField>
                  )}
                />
              </Grid>
              <Grid size={{ xs: 12, sm: 4 }}>
                <Controller
                  name="threshold"
                  control={control}
                  render={({ field }) => (
                    <TextField
                      {...field}
                      type="number"
                      label="Threshold"
                      fullWidth
                      size="small"
                      onChange={(e) => field.onChange(parseFloat(e.target.value))}
                      error={!!errors.threshold}
                      helperText={errors.threshold?.message}
                    />
                  )}
                />
              </Grid>
            </Grid>
          </Box>

          <Divider sx={{ mb: 3 }} />

          <Typography variant="subtitle1" sx={{ mb: 2, fontWeight: 'bold' }}>
            3. Action Strategy (THEN)
          </Typography>
          <Box sx={{ p: 2, bgcolor: 'background.default', borderRadius: 1 }}>
            <Grid container spacing={2}>
              <Grid size={{ xs: 12, sm: 6 }}>
                <Controller
                  name="action_type"
                  control={control}
                  render={({ field }) => (
                    <TextField
                      {...field}
                      select
                      label="Action Type"
                      fullWidth
                      size="small"
                      error={!!errors.action_type}
                      helperText={errors.action_type?.message}
                    >
                      <MenuItem value="CREATE_ALERT">Create System Alert</MenuItem>
                      <MenuItem value="EMAIL" disabled>Send Email (Coming Soon)</MenuItem>
                      <MenuItem value="WEBHOOK" disabled>Trigger Webhook (Coming Soon)</MenuItem>
                      <MenuItem value="MQTT_PUBLISH" disabled>MQTT Publish (Coming Soon)</MenuItem>
                    </TextField>
                  )}
                />
              </Grid>

              {actionType === 'CREATE_ALERT' && (
                <Grid size={{ xs: 12, sm: 6 }}>
                  <Controller
                    name="severity"
                    control={control}
                    render={({ field }) => (
                      <TextField
                        {...field}
                        select
                        label="Alert Severity"
                        fullWidth
                        size="small"
                        error={!!errors.severity}
                        helperText={errors.severity?.message}
                      >
                        <MenuItem value="INFO">Info</MenuItem>
                        <MenuItem value="WARNING">Warning</MenuItem>
                        <MenuItem value="CRITICAL">Critical</MenuItem>
                        <MenuItem value="EMERGENCY">Emergency</MenuItem>
                      </TextField>
                    )}
                  />
                </Grid>
              )}
            </Grid>
          </Box>

        </DialogContent>
        <DialogActions>
          <Button onClick={handleClose}>Cancel</Button>
          <Button type="submit" variant="contained">
            {initialData ? 'Save Changes' : 'Create Rule'}
          </Button>
        </DialogActions>
      </form>
    </Dialog>
  );
};
