import React, { useState } from 'react';
import { useForm, Controller } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import { z } from 'zod';
import {
  Zap,
  X,
  Tag,
  Radio,
  ChevronDown,
  FileText,
  Sliders,
  ShieldAlert,
  Layers
} from 'lucide-react';
import { HierarchySelector, type HierarchySelection } from '../../../components/HierarchySelector';
import { useSensorsQuery } from '../../sensors/hooks/useSensors';
import type { BackendRule, RuleCreate, RuleUpdate } from '../types';

const ruleSchema = z.object({
  code: z.string().min(2, 'Code must be at least 2 characters').regex(/^[a-zA-Z0-9_\-]+$/, 'Invalid characters'),
  name: z.string().min(2, 'Name must be at least 2 characters'),
  description: z.string().optional().or(z.literal('')),
  sensor_id: z.string().min(1, 'Sensor is required'),
  condition: z.enum(['>', '<', '>=', '<=', '==', '!=', 'BETWEEN', 'OUTSIDE RANGE']),
  threshold: z.number(),
  severity: z.enum(['INFO', 'WARNING', 'CRITICAL', 'EMERGENCY']),
  enabled: z.boolean(),
  cooldown_seconds: z.number().min(0),
  action_type: z.enum(['CREATE_ALERT', 'EMAIL', 'WEBHOOK', 'MQTT_PUBLISH', 'SMS', 'PUSH_NOTIFICATION']),
  action_config: z.record(z.string(), z.any()),
});

type RuleFormData = z.infer<typeof ruleSchema>;

export interface RuleFormProps {
  open: boolean;
  onClose: () => void;
  onSubmit: (data: RuleCreate | RuleUpdate) => void;
  initialData?: BackendRule;
  title: string;
}

export const RuleForm: React.FC<RuleFormProps> = ({ open, onClose, onSubmit, initialData, title }) => {
  const [hierarchy, setHierarchy] = useState<HierarchySelection>({
    orgId: '',
    tenantId: '',
    projectId: '',
    gatewayId: '',
    deviceId: '',
  });

  const { data: sensorsData } = useSensorsQuery(hierarchy.deviceId || '', 1, 100);

  const {
    control,
    handleSubmit,
    watch,
    setValue,
    reset,
    formState: { errors },
  } = useForm<RuleFormData>({
    resolver: zodResolver(ruleSchema),
    mode: 'onChange',
    defaultValues: initialData
      ? {
          code: initialData.code,
          name: initialData.name,
          description: initialData.description || '',
          sensor_id: initialData.sensor_id,
          condition: initialData.condition,
          threshold: initialData.threshold,
          severity: initialData.severity,
          enabled: initialData.enabled,
          cooldown_seconds: initialData.cooldown_seconds,
          action_type: initialData.action_type,
          action_config: initialData.action_config || {},
        }
      : {
          code: '',
          name: '',
          description: '',
          sensor_id: '',
          condition: '>',
          threshold: 0,
          severity: 'INFO',
          enabled: true,
          cooldown_seconds: 60,
          action_type: 'CREATE_ALERT',
          action_config: {},
        },
  });

  const actionType = watch('action_type');

  const handleClose = () => {
    reset();
    onClose();
  };

  const handleFormSubmit = (data: RuleFormData) => {
    if (data.action_type === 'CREATE_ALERT') {
      data.action_config = { message: `Alert generated by rule ${data.name}` };
    }
    onSubmit(data);
    handleClose();
  };

  if (!open) return null;

  return (
    <div 
      className="fixed inset-0 z-[9999] flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-sm animate-in fade-in duration-200"
      role="dialog"
      aria-modal="true"
      aria-labelledby="rule-modal-title"
    >
      {/* Modal Container */}
      <div className="relative w-full max-w-[780px] max-h-[90vh] bg-white rounded-[16px] shadow-2xl flex flex-col overflow-hidden animate-in zoom-in-95 duration-200 border border-slate-100 font-sans text-slate-800">
        
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-5 border-b border-slate-100 bg-white">
          <div className="flex items-center gap-3.5">
            <div className="w-11 h-11 rounded-xl bg-blue-50 text-[#2563EB] flex items-center justify-center border border-blue-100 shadow-xs">
              <Zap className="w-6 h-6" />
            </div>
            <div>
              <h2 id="rule-modal-title" className="text-xl font-bold text-slate-900 tracking-tight">
                {title}
              </h2>
              <p className="text-xs text-slate-500 mt-0.5">
                Configure telemetry condition rules and automated incident actions.
              </p>
            </div>
          </div>
          <button
            onClick={handleClose}
            className="w-9 h-9 rounded-lg flex items-center justify-center text-slate-400 hover:text-slate-700 hover:bg-slate-100 transition-all cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Scrollable Form Content */}
        <form id="rule-form" onSubmit={handleSubmit(handleFormSubmit)} className="flex-1 overflow-y-auto p-6 bg-[#F8FAFC] space-y-6">
          
          {/* Section 1: General Info */}
          <div className="space-y-4">
            <h3 className="text-xs font-bold text-slate-400 uppercase tracking-wider border-b border-slate-200/80 pb-2">
              1. General Rule Configuration
            </h3>

            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              {/* Code */}
              <Controller
                name="code"
                control={control}
                render={({ field, fieldState }) => (
                  <div className="flex flex-col gap-1.5">
                    <label className="text-xs font-semibold text-slate-700">
                      Rule Code <span className="text-rose-500">*</span>
                    </label>
                    <div className="relative flex items-center">
                      <Tag className="absolute left-3.5 w-4 h-4 text-slate-400 pointer-events-none" />
                      <input
                        {...field}
                        type="text"
                        disabled={!!initialData}
                        placeholder="e.g. RULE_TEMP_HIGH_01"
                        className={`w-full h-[48px] pl-10 pr-4 bg-white border ${
                          initialData ? 'bg-slate-100 text-slate-500 cursor-not-allowed border-slate-200' :
                          fieldState.error 
                            ? 'border-rose-400 focus:border-rose-500 focus:ring-4 focus:ring-rose-50' 
                            : 'border-[#DCE3EA] focus:border-[#2563EB] focus:ring-4 focus:ring-blue-50'
                        } rounded-[10px] text-sm text-slate-900 placeholder:text-slate-400 outline-none transition-all`}
                      />
                    </div>
                    {fieldState.error && !initialData && (
                      <span className="text-[11px] font-medium text-rose-500">{fieldState.error.message}</span>
                    )}
                  </div>
                )}
              />

              {/* Name */}
              <Controller
                name="name"
                control={control}
                render={({ field, fieldState }) => (
                  <div className="flex flex-col gap-1.5">
                    <label className="text-xs font-semibold text-slate-700">
                      Rule Name <span className="text-rose-500">*</span>
                    </label>
                    <div className="relative flex items-center">
                      <Zap className="absolute left-3.5 w-4 h-4 text-slate-400 pointer-events-none" />
                      <input
                        {...field}
                        type="text"
                        placeholder="Enter rule name"
                        className={`w-full h-[48px] pl-10 pr-4 bg-white border ${
                          fieldState.error 
                            ? 'border-rose-400 focus:border-rose-500 focus:ring-4 focus:ring-rose-50' 
                            : 'border-[#DCE3EA] focus:border-[#2563EB] focus:ring-4 focus:ring-blue-50'
                        } rounded-[10px] text-sm text-slate-900 placeholder:text-slate-400 outline-none transition-all`}
                      />
                    </div>
                    {fieldState.error && (
                      <span className="text-[11px] font-medium text-rose-500">{fieldState.error.message}</span>
                    )}
                  </div>
                )}
              />
            </div>

            {/* Description */}
            <Controller
              name="description"
              control={control}
              render={({ field }) => (
                <div className="flex flex-col gap-1.5">
                  <label className="text-xs font-semibold text-slate-700">
                    Description
                  </label>
                  <div className="relative">
                    <FileText className="absolute left-3.5 top-3.5 w-4 h-4 text-slate-400 pointer-events-none" />
                    <textarea
                      {...field}
                      rows={2}
                      placeholder="Describe automation threshold triggers and severity level..."
                      className="w-full pl-10 pr-4 pt-3 pb-3 bg-white border border-[#DCE3EA] focus:border-[#2563EB] focus:ring-4 focus:ring-blue-50 rounded-[10px] text-sm text-slate-900 placeholder:text-slate-400 outline-none transition-all resize-none min-h-[75px]"
                    />
                  </div>
                </div>
              )}
            />
          </div>

          {/* Section 2: Trigger Condition (IF) */}
          <div className="space-y-4 pt-2">
            <h3 className="text-xs font-bold text-slate-400 uppercase tracking-wider border-b border-slate-200/80 pb-2">
              2. Trigger Condition (IF)
            </h3>

            {!initialData && (
              <div className="bg-white border border-slate-200 p-4 rounded-xl space-y-2">
                <span className="text-xs font-bold text-slate-500 flex items-center gap-1.5">
                  <Layers className="w-3.5 h-3.5 text-[#2563EB]" /> Select Target Device Scope
                </span>
                <HierarchySelector
                  selection={hierarchy}
                  onChange={(sel) => {
                    setHierarchy(sel);
                    setValue('sensor_id', '');
                  }}
                  maxDepth="device"
                  variant="dropdown"
                />
              </div>
            )}

            <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
              {/* Sensor */}
              <Controller
                name="sensor_id"
                control={control}
                render={({ field, fieldState }) => (
                  <div className="flex flex-col gap-1.5">
                    <label className="text-xs font-semibold text-slate-700">
                      Target Sensor <span className="text-rose-500">*</span>
                    </label>
                    <div className="relative flex items-center">
                      <Radio className="absolute left-3.5 w-4 h-4 text-slate-400 pointer-events-none" />
                      <select
                        {...field}
                        disabled={!!initialData || !hierarchy.deviceId}
                        className="w-full h-[48px] pl-10 pr-8 bg-white border border-[#DCE3EA] rounded-[10px] text-sm font-medium text-slate-900 appearance-none focus:border-[#2563EB] focus:ring-4 focus:ring-blue-50 outline-none transition-all cursor-pointer disabled:bg-slate-100 disabled:text-slate-400 disabled:cursor-not-allowed"
                      >
                        <option value="">Select Sensor...</option>
                        {sensorsData?.items.map((sensor) => (
                          <option key={sensor.id} value={sensor.id}>
                            {sensor.name} ({sensor.code})
                          </option>
                        ))}
                      </select>
                      <ChevronDown className="absolute right-3.5 w-4 h-4 text-slate-400 pointer-events-none" />
                    </div>
                    {fieldState.error && (
                      <span className="text-[11px] font-medium text-rose-500">{fieldState.error.message}</span>
                    )}
                  </div>
                )}
              />

              {/* Operator */}
              <Controller
                name="condition"
                control={control}
                render={({ field }) => (
                  <div className="flex flex-col gap-1.5">
                    <label className="text-xs font-semibold text-slate-700">
                      Operator Condition
                    </label>
                    <div className="relative flex items-center">
                      <Sliders className="absolute left-3.5 w-4 h-4 text-slate-400 pointer-events-none" />
                      <select
                        {...field}
                        className="w-full h-[48px] pl-10 pr-8 bg-white border border-[#DCE3EA] rounded-[10px] text-sm font-medium text-slate-900 appearance-none focus:border-[#2563EB] focus:ring-4 focus:ring-blue-50 outline-none transition-all cursor-pointer"
                      >
                        <option value=">">Greater than (&gt;)</option>
                        <option value="<">Less than (&lt;)</option>
                        <option value=">=">Greater or equal (&gt;=)</option>
                        <option value="<=">Less or equal (&lt;=)</option>
                        <option value="==">Equals (==)</option>
                        <option value="!=">Not equal (!=)</option>
                      </select>
                      <ChevronDown className="absolute right-3.5 w-4 h-4 text-slate-400 pointer-events-none" />
                    </div>
                  </div>
                )}
              />

              {/* Threshold */}
              <Controller
                name="threshold"
                control={control}
                render={({ field }) => (
                  <div className="flex flex-col gap-1.5">
                    <label className="text-xs font-semibold text-slate-700">
                      Threshold Value
                    </label>
                    <input
                      type="number"
                      value={field.value}
                      onChange={(e) => field.onChange(parseFloat(e.target.value) || 0)}
                      className="w-full h-[48px] px-4 bg-white border border-[#DCE3EA] focus:border-[#2563EB] focus:ring-4 focus:ring-blue-50 rounded-[10px] text-sm text-slate-900 outline-none transition-all font-mono"
                    />
                  </div>
                )}
              />
            </div>
          </div>

          {/* Section 3: Action Strategy (THEN) */}
          <div className="space-y-4 pt-2">
            <h3 className="text-xs font-bold text-slate-400 uppercase tracking-wider border-b border-slate-200/80 pb-2">
              3. Action Strategy (THEN)
            </h3>

            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              {/* Action Type */}
              <Controller
                name="action_type"
                control={control}
                render={({ field }) => (
                  <div className="flex flex-col gap-1.5">
                    <label className="text-xs font-semibold text-slate-700">
                      Action Type
                    </label>
                    <div className="relative flex items-center">
                      <Zap className="absolute left-3.5 w-4 h-4 text-slate-400 pointer-events-none" />
                      <select
                        {...field}
                        className="w-full h-[48px] pl-10 pr-8 bg-white border border-[#DCE3EA] rounded-[10px] text-sm font-medium text-slate-900 appearance-none focus:border-[#2563EB] focus:ring-4 focus:ring-blue-50 outline-none transition-all cursor-pointer"
                      >
                        <option value="CREATE_ALERT">🚨 Create System Alert</option>
                        <option value="EMAIL" disabled>📧 Send Email (Coming Soon)</option>
                        <option value="WEBHOOK" disabled>🔗 Trigger Webhook (Coming Soon)</option>
                        <option value="MQTT_PUBLISH" disabled>📡 MQTT Publish (Coming Soon)</option>
                      </select>
                      <ChevronDown className="absolute right-3.5 w-4 h-4 text-slate-400 pointer-events-none" />
                    </div>
                  </div>
                )}
              />

              {/* Severity */}
              {actionType === 'CREATE_ALERT' && (
                <Controller
                  name="severity"
                  control={control}
                  render={({ field }) => (
                    <div className="flex flex-col gap-1.5">
                      <label className="text-xs font-semibold text-slate-700">
                        Alert Severity
                      </label>
                      <div className="relative flex items-center">
                        <ShieldAlert className="absolute left-3.5 w-4 h-4 text-slate-400 pointer-events-none" />
                        <select
                          {...field}
                          className="w-full h-[48px] pl-10 pr-8 bg-white border border-[#DCE3EA] rounded-[10px] text-sm font-medium text-slate-900 appearance-none focus:border-[#2563EB] focus:ring-4 focus:ring-blue-50 outline-none transition-all cursor-pointer"
                        >
                          <option value="INFO">🔵 Info</option>
                          <option value="WARNING">🟠 Warning</option>
                          <option value="CRITICAL">🔴 Critical</option>
                          <option value="EMERGENCY">🔥 Emergency</option>
                        </select>
                        <ChevronDown className="absolute right-3.5 w-4 h-4 text-slate-400 pointer-events-none" />
                      </div>
                    </div>
                  )}
                />
              )}
            </div>
          </div>

        </form>

        {/* Footer Actions */}
        <div className="flex items-center justify-end gap-3 px-6 py-4 border-t border-slate-100 bg-white">
          <button
            type="button"
            onClick={handleClose}
            className="px-5 py-2.5 bg-transparent hover:bg-slate-100 border border-slate-300 text-slate-700 rounded-xl text-sm font-semibold transition-all cursor-pointer"
          >
            Cancel
          </button>
          
          <button
            type="submit"
            form="rule-form"
            className="px-5 py-2.5 bg-[#2563EB] hover:bg-blue-700 active:bg-blue-800 text-white rounded-xl text-sm font-semibold shadow-sm hover:shadow-md flex items-center gap-2 transition-all cursor-pointer"
          >
            <Zap className="w-4 h-4" />
            <span>{initialData ? 'Save Changes' : 'Create Rule'}</span>
          </button>
        </div>

      </div>
    </div>
  );
};
